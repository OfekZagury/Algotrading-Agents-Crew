import pandas as pd
import pandas_ta as ta
import yfinance as yf
from datetime import datetime
from diskcache import Cache
from crewai.tools import tool
from core.logger import setup_logger
from typing import Annotated

logger = setup_logger()


# Initialize file-based cache
cache = Cache(".cache", size_limit=int(1e9), eviction_policy='least-recently-used')

@tool("get_historical_data of candlestick data")
def get_historical_data(
        symbol: Annotated[str, "The stock ticker (e.g., 'AAPL')."],
        period: Annotated[str, "Data period to download (e.g., '1mo', '3mo', '1y')."] = "1mo"
    ) -> str:
    """
    Fetches historical OHLCV (Open, High, Low, Close, Volume) data.
    Returns:
        str: A string representation of the DataFrame (last 5 rows) for the agent to review.
    """
    # Create cache key
    cache_key = f"hist_{symbol}_{period}_{datetime.now().strftime('%Y-%m-%d_%H')}"

    if cache_key in cache:
        return cache[cache_key]

    logger.info(f"Fetching historical data for {symbol}...")

    try:
        # Download data using yfinance
        df = yf.Ticker(symbol).history(period=period)

        if df.empty:
            return f"No data found for symbol {symbol}"

        # We only return the tail (last 5 days) to avoid overwhelming the LLM context window
        # The agent needs to see the raw numbers of recent price action
        result_str = df.tail(10).to_string()

        cache[cache_key] = result_str
        return result_str

    except Exception as e:
        return f"Error fetching historical data: {str(e)}"


@tool("calculate RSI and MACD values and determine trend")
def calculate_indicators(
        symbol: Annotated[str, "The stock ticker (e.g., 'AAPL')."],
    ) -> dict:
    """
    Calculates technical indicators (RSI, MACD) for the given stock.
    Returns:
        dict: A dictionary containing the latest RSI, MACD Line, Signal Line, and a calculated Trend.
    """
    # Cache key (valid for the current hour)
    cache_key = f"indicators_{symbol}_{datetime.now().strftime('%Y-%m-%d_%H')}"

    if cache_key in cache:
        return cache[cache_key]

    logger.info(f"Calculating indicators for {symbol}...")

    try:
        # Fetch enough data for MACD (requires at least 26 periods)
        # We fetch 3 months to be safe and accurate
        df = yf.Ticker(symbol).history(period="3mo")

        if df.empty or len(df) < 26:
            return {"error": "Insufficient data for calculations"}

        # --- Calculate RSI (Relative Strength Index) ---
        # Standard length is 14
        df['RSI'] = df.ta.rsi(length=14)

        # --- Calculate MACD (Moving Average Convergence Divergence) ---
        # Fast=12, Slow=26, Signal=9
        macd = df.ta.macd(fast=12, slow=26, signal=9)

        # pandas_ta returns columns with names like 'MACD_12_26_9', 'MACDh_...', 'MACDs_...'
        # We join these columns back to the main DataFrame
        df = pd.concat([df, macd], axis=1)

        # Get the latest (most recent) row of data
        latest = df.iloc[-1]

        # Extract specific column names generated by pandas_ta
        # Note: These names depend on the parameters passed to ta.macd()
        macd_col = 'MACD_12_26_9'
        signal_col = 'MACDs_12_26_9'

        # Check if columns exist (sanity check)
        if macd_col not in df.columns:
            return {"error": "MACD calculation failed"}

        # Extract values
        rsi_val = latest['RSI']
        macd_val = latest[macd_col]
        signal_val = latest[signal_col]

        # Determine Trend based on MACD crossover
        # If MACD line > Signal line => Bullish
        trend = "Bullish" if macd_val > signal_val else "Bearish"

        # Construct the result dictionary
        result = {
            "symbol": symbol,
            "RSI": round(float(rsi_val), 2),
            "MACD_Line": round(float(macd_val), 4),
            "Signal_Line": round(float(signal_val), 4),
            "Trend": trend,
            "Price": round(float(latest['Close']), 2)  # Adding current price for context
        }

        cache[cache_key] = result
        return result

    except Exception as e:
        return {"error": f"Calculation failed: {str(e)}"}